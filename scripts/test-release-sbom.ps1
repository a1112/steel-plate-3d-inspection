  $VerifyArgs = @{
    SbomPath = $OutputOne
    RepoRoot = $FixtureRepo
    ExternalComponentsPath = $ExternalPath
    ExpectedExternalComponentsSha256 = $ExternalHash
    ExpectedCommit = $Commit
  }
  $Cases += ,(Invoke-ShouldPass 'offline semantic verification' { & $Verifier @VerifyArgs })

  $GenerateArgs.OutputPath = $OutputTwo
  $Cases += ,(Invoke-ShouldPass 'second deterministic generation' { & $Generator @GenerateArgs })
  if ((Get-Sha256Hex $OutputOne) -cne (Get-Sha256Hex $OutputTwo)) {
    throw 'Repeated generation from the same commit and evidence was not byte-for-byte deterministic.'
  }
  $Cases += ,[ordered]@{ name = 'deterministic output hash'; passed = $true; expected = 'identical' }

  Copy-Item -LiteralPath $OutputOne -Destination $TamperedSbom
  $Tampered = Read-JsonDictionary $TamperedSbom
  $Tampered['components'][0]['version'] = '99.99.99'
