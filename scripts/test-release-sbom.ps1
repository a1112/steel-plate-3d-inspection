"@
    Write-Utf8NoBom -Path (Join-Path $FixtureRepo $Definition.path) -Content ($CargoLock.TrimStart() + "`n")
  }

  $ExternalRows = @(
    [ordered]@{ id = 'msvc'; category = 'cpp-toolchain'; type = 'application'; name = 'MSVC Build Tools'; version = '14.40.33807'; supplier = 'Microsoft Corporation'; scope = 'build'; artifact = 'vs_buildtools.exe'; purl = 'pkg:generic/msvc-build-tools@14.40.33807'; licenses = @('LicenseRef-Microsoft-Visual-Studio') },
    [ordered]@{ id = 'camera-sdk'; category = 'camera-sdk'; type = 'library'; name = 'Fixture Camera SDK'; version = '5.4.3'; supplier = 'Fixture Camera Vendor'; scope = 'runtime'; artifact = 'nvt_lvm_sdk.dll'; purl = 'pkg:generic/fixture-camera-sdk@5.4.3'; licenses = @('LicenseRef-Fixture-Proprietary') },
    [ordered]@{ id = 'vc-redist'; category = 'vc-runtime'; type = 'application'; name = 'VC++ Redistributable x64'; version = '14.40.33810'; supplier = 'Microsoft Corporation'; scope = 'runtime'; artifact = 'VC_redist.x64.exe'; purl = 'pkg:generic/vc-redist-x64@14.40.33810'; licenses = @('LicenseRef-Microsoft-Visual-Cpp-Runtime') },
    [ordered]@{ id = 'webview2'; category = 'webview2-runtime'; type = 'framework'; name = 'WebView2 Runtime x64'; version = '126.0.0.0'; supplier = 'Microsoft Corporation'; scope = 'runtime'; artifact = 'MicrosoftEdgeWebView2RuntimeInstallerX64.exe'; purl = 'pkg:generic/webview2-runtime-x64@126.0.0.0'; licenses = @('LicenseRef-Microsoft-WebView2-Runtime') },
