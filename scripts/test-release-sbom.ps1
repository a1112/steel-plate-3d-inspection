        integrity = Get-TestSriSha512 '@scope/dev-tool-2.0.0'
        dev = $true
        license = 'Apache-2.0'
      }
    }
  }
  Write-Utf8NoBom -Path (Join-Path $FixtureRepo 'app\client\package-lock.json') -Content (($PackageLock | ConvertTo-Json -Depth 20) + "`n")

  $RegistryChecksum = Get-TestDigest 'serde-1.0.0'
  $CargoDefinitions = @(
    [ordered]@{ path = 'app\client\src-tauri\Cargo.lock'; root = 'fixture-tauri' },
    [ordered]@{ path = 'app\service\Cargo.lock'; root = 'fixture-service' },
    [ordered]@{ path = 'app\trigger\Cargo.lock'; root = 'fixture-trigger' }
  )
  foreach ($Definition in $CargoDefinitions) {
    $CargoLock = @"
# This file is automatically @generated by Cargo.
