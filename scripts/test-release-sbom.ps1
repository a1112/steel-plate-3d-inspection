  $ProtectedOutputArgs.OutputPath = Join-Path $FixtureRepo 'app\client\package-lock.json'
  $Cases += ,(Invoke-ShouldFail 'SBOM input overwrite rejected' { & $Generator @ProtectedOutputArgs })

  $MissingCategoryConfig = [ordered]@{
    schema = 'steel.release-external-components.v1'
    approved = $true
    components = @($ExternalRows | Where-Object { $_.category -ne 'nsis' })
  }
  $MissingCategoryPath = Join-Path $TestRoot 'missing-category.json'
