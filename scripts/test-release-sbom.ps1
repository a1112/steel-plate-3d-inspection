  Write-Utf8NoBom -Path $TamperedToolsSbom -Content (($TamperedTools | ConvertTo-Json -Depth 100) + "`n")
  $TamperedToolsArgs = $VerifyArgs.Clone()
  $TamperedToolsArgs.SbomPath = $TamperedToolsSbom
  $Cases += ,(Invoke-ShouldFail 'tampered generator environment rejected' { & $Verifier @TamperedToolsArgs })

  Add-Content -LiteralPath (Join-Path $FixtureRepo 'app\service\Cargo.lock') -Value '# lock tamper' -Encoding ascii
  $DirtyVerifyArgs = $VerifyArgs.Clone()
  $DirtyVerifyArgs.AllowDirtyWorktree = $true
  $Cases += ,(Invoke-ShouldFail 'changed lock hash rejected' { & $Verifier @DirtyVerifyArgs })
  $DirtyGenerateArgs = $GenerateArgs.Clone()
  $DirtyGenerateArgs.OutputPath = Join-Path $TestRoot 'dirty.cdx.json'
  $Cases += ,(Invoke-ShouldFail 'dirty source rejected by default' { & $Generator @DirtyGenerateArgs })
