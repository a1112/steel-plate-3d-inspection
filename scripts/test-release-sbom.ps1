  & git -C $FixtureRepo init --quiet
  if ($LASTEXITCODE -ne 0) { throw 'git init failed for SBOM fixture.' }
  & git -C $FixtureRepo config user.email 'sbom-test@example.invalid'
  & git -C $FixtureRepo config user.name 'SBOM Test'
  & git -C $FixtureRepo add --all
  & git -C $FixtureRepo commit --quiet -m 'SBOM fixture'
  if ($LASTEXITCODE -ne 0) { throw 'git commit failed for SBOM fixture.' }
  $Commit = ((& git -C $FixtureRepo rev-parse HEAD) | Out-String).Trim().ToLowerInvariant()
  $ExternalHash = Get-Sha256Hex $ExternalPath

  $env:HTTP_PROXY = 'http://127.0.0.1:1'
  $env:HTTPS_PROXY = 'http://127.0.0.1:1'
