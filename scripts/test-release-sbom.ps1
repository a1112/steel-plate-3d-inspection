    [ordered]@{ id = 'nsis'; category = 'nsis'; type = 'application'; name = 'NSIS'; version = '3.10'; supplier = 'NSIS Contributors'; scope = 'build'; artifact = 'nsis-3.10.zip'; purl = 'pkg:generic/nsis@3.10'; licenses = @('Zlib') }
  )
  foreach ($Row in $ExternalRows) { $Row['sha256'] = Get-TestDigest ([string]$Row.artifact) }
