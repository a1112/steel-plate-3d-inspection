function Write-Utf8NoBom {
  param(
    [Parameter(Mandatory = $true)][string]$Path,
    [Parameter(Mandatory = $true)][string]$Content
  )

  $Parent = Split-Path -Parent $Path
  if (-not (Test-Path -LiteralPath $Parent -PathType Container)) {
    New-Item -ItemType Directory -Path $Parent -Force | Out-Null
  }
  [System.IO.File]::WriteAllText($Path, $Content, [System.Text.UTF8Encoding]::new($false))
}

function Get-TestDigest {
  param([Parameter(Mandatory = $true)][string]$Value)
  return Get-StringSha256Hex $Value
}

function Get-TestSriSha512 {
  param([Parameter(Mandatory = $true)][string]$Value)

  $Algorithm = [System.Security.Cryptography.SHA512]::Create()
  try {
    $Digest = $Algorithm.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($Value))
    return 'sha512-' + [Convert]::ToBase64String($Digest)
  } finally {
    $Algorithm.Dispose()
  }
}

function Invoke-ShouldPass {
  param(
    [Parameter(Mandatory = $true)][string]$Label,
    [Parameter(Mandatory = $true)][scriptblock]$Action
  )
  try {
    & $Action | Out-Null
    return [ordered]@{ name = $Label; passed = $true; expected = 'success' }
  } catch {
    throw "Expected success for '$Label': $($_.Exception.Message)"
  }
}

function Invoke-ShouldFail {
  param(
    [Parameter(Mandatory = $true)][string]$Label,
    [Parameter(Mandatory = $true)][scriptblock]$Action
  )
  try {
    & $Action | Out-Null
  } catch {
    return [ordered]@{ name = $Label; passed = $true; expected = 'failure'; message = $_.Exception.Message }
  }
  throw "Expected failure for '$Label', but the command succeeded."
}

